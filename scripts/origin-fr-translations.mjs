export function findRemainingChineseStringLiterals(source) {
  const script = source.match(/<script>([\s\S]*?)<\/script>/)?.[1] ?? source;
  const withoutComments = script.replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|[^:])\/\/.*$/gm, '$1');
  const literals = withoutComments.match(/(['"`])(?:\\.|(?!\1)[\s\S])*?\1/g) ?? [];
  const remaining = new Set();
  for (const literal of literals) if (HAN.test(literal)) remaining.add(literal.slice(0, 300));
  return [...remaining].sort();
}
